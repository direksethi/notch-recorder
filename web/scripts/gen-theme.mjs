// Turns theme/notch-dark.json (oklch colours) into CSS variables for the Library
// and a Swift enum for the native notch UI, so both share one palette.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { converter, formatHex, parse } from "culori"

const root = new URL("../../", import.meta.url)
const theme = JSON.parse(readFileSync(new URL("theme/notch-dark.json", root), "utf8"))
const toRgb = converter("rgb")

const clamp = (v) => Math.min(1, Math.max(0, v))
const rgbOf = (value) => {
  const c = toRgb(parse(value))
  return { r: clamp(c.r), g: clamp(c.g), b: clamp(c.b) }
}
const kebab = (k) => k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)

// Speaker and recording colours the theme file does not define.
const extra = {
  speakerMe: "oklch(0.72 0.12 245)",
  speakerOthers: "oklch(0.74 0.11 305)",
  recording: "oklch(0.64 0.2 25)",
}
const colors = { ...theme.colors, ...extra }

const css = [
  `/* Generated by web/scripts/gen-theme.mjs from theme/notch-dark.json. Do not edit. */`,
  `:root {`,
  `  color-scheme: ${theme.appearance};`,
  ...Object.entries(colors).map(([k, v]) => `  --${kebab(k)}: ${v};`),
  `}`,
  "",
].join("\n")
const cssOut = new URL("web/apps/library/src/theme.css", root)
mkdirSync(new URL(".", cssOut), { recursive: true })
writeFileSync(cssOut, css)

const swift = [
  `// Generated by web/scripts/gen-theme.mjs from theme/notch-dark.json. Do not edit.`,
  `import SwiftUI`,
  ``,
  `public enum Theme {`,
  ...Object.entries(colors).map(([k, v]) => {
    const { r, g, b } = rgbOf(v)
    return `    public static let ${k} = Color(.sRGB, red: ${r.toFixed(4)}, green: ${g.toFixed(4)}, blue: ${b.toFixed(4)}) // ${formatHex({ mode: "rgb", r, g, b })}`
  }),
  `}`,
  "",
].join("\n")
writeFileSync(new URL("Sources/LiveUI/Theme.generated.swift", root), swift)
console.log(`theme: ${Object.keys(colors).length} colours`)
